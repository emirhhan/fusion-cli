"""Cevaptaki 'captcha' kelimesi çalışan oturumu düşürmemeli; gerçek doğrulama yakalanmalı."""

import asyncio

from fusion_cli.providers import web_browser as wb


class _Konum:
    def __init__(self, sayi: int) -> None:
        self._sayi = sayi

    async def count(self) -> int:
        return self._sayi


class _Sayfa:
    def __init__(self, baslik: str = "ChatGPT", dom_sayisi: int = 0) -> None:
        self._baslik = baslik
        self._dom = dom_sayisi

    async def title(self) -> str:
        return self._baslik

    def locator(self, _selector: str) -> _Konum:
        return _Konum(self._dom)


def _sinyal(sayfa: _Sayfa, govde: str, *, kutu_gorunur: bool, monkeypatch) -> str | None:
    async def gorunur(_sayfa, _secici) -> bool:
        return kutu_gorunur

    monkeypatch.setattr(wb, "_any_visible", gorunur)
    tanim = wb.provider_definition("chatgpt_web")
    return asyncio.run(wb._challenge_signal(sayfa, tanim, body=govde))


def test_mesaj_kutusu_gorunurken_cevaptaki_captcha_kelimesi_kanit_degildir(monkeypatch) -> None:
    govde = "vfs kullanım koşulları captcha kullanımını ve otomatik erişimi sınırlar"
    assert _sinyal(_Sayfa(), govde, kutu_gorunur=True, monkeypatch=monkeypatch) is None


def test_mesaj_kutusu_yokken_gercek_dogrulama_metni_yakalanir(monkeypatch) -> None:
    assert _sinyal(_Sayfa(), "verify you are human", kutu_gorunur=False, monkeypatch=monkeypatch)


def test_baslik_ara_sayfasi_her_durumda_yakalanir(monkeypatch) -> None:
    sayfa = _Sayfa(baslik="Bir dakika lütfen...")
    assert _sinyal(sayfa, "", kutu_gorunur=True, monkeypatch=monkeypatch)


def test_cloudflare_dom_kaniti_yakalanir(monkeypatch) -> None:
    sayfa = _Sayfa(dom_sayisi=1)
    sonuc = _sinyal(sayfa, "", kutu_gorunur=True, monkeypatch=monkeypatch)
    assert sonuc == "cloudflare doğrulaması"


def test_gecerli_nesnenin_arkasindaki_artik_cagriyi_bozmaz() -> None:
    from fusion_cli.engines.agent.loop_contract import _parse_arguments_checked

    sonuc, hata = _parse_arguments_checked('{"query": "vfs"} {"query": "ikinci"}')
    assert hata is None and sonuc == {"query": "vfs"}
    sonuc, hata = _parse_arguments_checked('{"query": "vfs"}\n```\nFUSION_TOOL_CALL_END')
    assert hata is None and sonuc == {"query": "vfs"}
    _bos, hata = _parse_arguments_checked('{"query": "yarım')
    assert hata is not None and "geçerli JSON" in hata


def test_bozuk_arguman_gecmise_gecerli_json_olarak_gider() -> None:
    from fusion_cli.providers.litellm_provider import _valid_arguments

    assert _valid_arguments('{"query": "a"}') == '{"query": "a"}'
    assert _valid_arguments('{"query": "a"} {"query": "b"}') == '{"query": "a"}'
    assert _valid_arguments('{"query": "yarım') == "{}"
    assert _valid_arguments("düz metin") == "{}"


def test_generated_kelimesi_hiz_siniri_sayilmaz() -> None:
    from fusion_cli.engines.agent.loop import _short_reason

    assert _short_reason("JSONDecodeError ... Auto-generated by LiteLLM") == "yanıt veremedi"
    assert _short_reason("RateLimitError 429 too many requests") == "hız sınırına takıldı"
